// Run after client_comments_access.php --setup; fixture cleanup is a separate CLI step.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
(async () => {
  const fixture = JSON.parse(fs.readFileSync(process.env.CLIENT_COMMENTS_FIXTURE || '/private/tmp/gammavet-client-comments-fixture.json', 'utf8'));
  const browser = await chromium.launch({ headless: true });
  try {
    const context = await browser.newContext();
    await context.addCookies([{ name: 'PHPSESSID', value: fixture.session, url: 'http://localhost:8080/' }]);
    const page = await context.newPage();
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.goto(`http://localhost:8080/modules/inventories/view.php?id=${fixture.inventories[0]}`);
    await page.waitForFunction(() => window.jQuery?.fn.dataTable?.isDataTable(document.querySelector('table.js-datatable')));
    const initialCount = await page.evaluate(() => window.jQuery('table.js-datatable').DataTable().rows().count());
    const moveToSecondPage = () => page.evaluate(() => window.jQuery('table.js-datatable').DataTable().page(1).draw(false));
    await moveToSecondPage();
    const editButton = page.locator('tbody .edit-product').first();
    const selectedId = await editButton.getAttribute('data-id');
    assert(fixture.products.includes(Number(selectedId)));
    await editButton.locator('i').click();
    await page.waitForSelector('#editProductModal.show');
    assert.equal(await page.locator('#edit_product_id').inputValue(), selectedId);
    await page.locator('#edit_quantity').fill('17');
    await page.locator('#editProductModal button[type="submit"]').click();
    await page.waitForLoadState('domcontentloaded');
    await page.waitForFunction(() => window.jQuery?.fn.dataTable?.isDataTable(document.querySelector('table.js-datatable')));
    await moveToSecondPage();
    const edited = page.locator(`.edit-product[data-id="${selectedId}"]`);
    assert.equal(Number(await edited.getAttribute('data-quantity')), 17);
    console.log('PASS Edit opens from an icon on a later page and updates the selected item');
    const remove = page.locator('tbody .remove-product').first();
    const removeId = await remove.getAttribute('data-product-id');
    await remove.locator('i').click();
    await page.waitForSelector('#removeProductModal.show');
    assert.equal(await page.locator('#remove_product_id').inputValue(), removeId);
    await page.locator('#removeProductModal button[data-bs-dismiss="modal"]').last().click();
    await page.waitForSelector('#removeProductModal.show', { state: 'hidden' });
    assert.equal(await page.locator(`.remove-product[data-product-id="${removeId}"]`).count(), 1);
    console.log('PASS Remove opens the correct modal after pagination; cancel preserves the item');
    await page.locator(`.remove-product[data-product-id="${removeId}"]`).click();
    await page.waitForSelector('#removeProductModal.show');
    await page.locator('#confirmRemoveBtn').click();
    await page.waitForLoadState('domcontentloaded');
    await page.waitForFunction(() => window.jQuery?.fn.dataTable?.isDataTable(document.querySelector('table.js-datatable')));
    const ids = await page.evaluate(() => window.jQuery('table.js-datatable').DataTable().rows().nodes().toArray().flatMap(row => [...row.querySelectorAll('.remove-product')].map(button => button.dataset.productId)));
    assert(!ids.includes(removeId));
    assert.equal(ids.length, initialCount - 1);
    console.log('PASS Confirm Remove deletes only the selected fixture item');
    await page.goto('http://localhost:8080/modules/manufacturing/');
    await page.waitForFunction(() => window.jQuery?.fn.dataTable?.isDataTable(document.querySelector('#manufacturingTable')));
    assert.equal(await page.locator('th', { hasText: 'Points to Check' }).count(), 0);
    console.log('PASS Manufacturing list renders with the audit column omitted');
    await page.goto(`http://localhost:8080/modules/inventories/index.php?location_id=${fixture.locations[0]}`);
    await page.waitForFunction(() => window.jQuery?.fn.dataTable?.isDataTable(document.querySelector('table.js-datatable')));
    assert.equal(await page.locator('#inventoryLocation').inputValue(), String(fixture.locations[0]));
    assert.equal(await page.locator('tbody .edit-inventory').count(), 1);
    await page.locator(`.edit-inventory[data-id="${fixture.inventories[0]}"] i`).click();
    await page.waitForSelector('#editInventoryModal.show');
    assert.equal(await page.locator('#edit_id').inputValue(), String(fixture.inventories[0]));
    console.log('PASS Location filter and warehouse Edit select the correct warehouse');
    await page.locator('#editInventoryModal button[data-bs-dismiss="modal"]').last().click();
    await page.waitForSelector('#editInventoryModal.show', { state: 'hidden' });
    const download = page.waitForEvent('download');
    await page.locator('.js-export-filtered').click();
    const csv = await download;
    const csvPath = await csv.path();
    const csvText = fs.readFileSync(csvPath, 'utf8');
    assert(csvText.includes(String(fixture.inventories[0])));
    console.log('PASS Filtered warehouse CSV downloads');
    assert.deepEqual(errors, []);
    console.log('PASS No browser JavaScript errors');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
